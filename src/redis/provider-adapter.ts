import { createRedisKeys, RedisStoreError, validateStoreOptions, type StoreOptions } from './shared.js';

type Payload = Record<string, unknown>;
export interface RedisProviderAdapterOptions extends StoreOptions {
    /** Supply the real provider error constructor, e.g. () => new errors.InvalidGrant(). */
    invalidGrant: () => Error;
}

export interface RedisProviderAdapter {
    upsert(id: string, payload: Payload, expiresIn: number): Promise<void>;
    find(id: string): Promise<Payload | undefined>;
    findByUid(uid: string): Promise<Payload | undefined>;
    findByUserCode(userCode: string): Promise<Payload | undefined>;
    consume(id: string): Promise<void>;
    destroy(id: string): Promise<void>;
    revokeByGrantId(grantId: string): Promise<void>;
    getGrantBinding(grantId: string): Promise<{ bindingId: string; version: number } | undefined>;
}

const grantable = new Set(['AccessToken', 'AuthorizationCode', 'RefreshToken', 'DeviceCode', 'BackchannelAuthenticationRequest', 'PreAuthorizedCode']);
const requiresGrant = new Set(['AccessToken', 'AuthorizationCode', 'RefreshToken']);
const MAX_PAYLOAD_BYTES = 65_536;

// Every operation is one server-side transaction. Stored key references are generated by
// createRedisKeys, never read from provider payloads. This topology targets standalone Redis.
const common = `
local now = tonumber(redis.call('TIME')[1])
local function decode(value)
  if not value then return nil end
  local ok, result = pcall(cjson.decode, value)
  if not ok or type(result) ~= 'table' then return nil end
  return result
end
local function live(key)
  local raw = redis.call('HGET', key, 'payload')
  local payload = decode(raw)
  local expires = tonumber(redis.call('HGET', key, 'expiresAt') or '0')
  if not payload or expires <= now then return nil end
  return payload, raw
end
local function grant(key)
  local payload, raw = live(key)
  if not payload or type(payload.exp) ~= 'number' or payload.exp <= now then return nil end
  local revoked = redis.call('HGET', key, 'revokedKey')
  if not revoked or redis.call('EXISTS', revoked) == 1 then return nil end
  local binding = redis.call('HGET', key, 'bindingKey')
  local version = redis.call('HGET', key, 'bindingVersion')
  local bindingId = redis.call('HGET', key, 'bindingId')
  if not binding or not version or not bindingId or payload.accountId ~= bindingId then return nil end
  if redis.call('HGET', binding, 'active') ~= '1' or redis.call('HGET', binding, 'version') ~= version then return nil end
  return payload, raw, bindingId, version
end
local function valid(key, mode)
  if mode == 'grant' then return grant(key) end
  local payload, raw = live(key)
  if not payload then return nil end
  local grantKey = redis.call('HGET', key, 'grantKey')
  if grantKey and grantKey ~= '' then
    local revoked = redis.call('HGET', key, 'revokedKey')
    if not revoked or redis.call('EXISTS', revoked) == 1 then return nil end
    local parent = grant(grantKey)
    if not parent or payload.accountId ~= parent.accountId or payload.clientId ~= parent.clientId then return nil end
  elseif mode == 'token' then return nil end
  return payload, raw
end
local function removeIndexes(key, id)
  for _, field in ipairs({'uidIndex', 'userCodeIndex'}) do
    local index = redis.call('HGET', key, field)
    if index and index ~= '' and redis.call('GET', index) == id then redis.call('DEL', index) end
  end
end
local function revoke(grantKey, revokedKey, ttl)
  redis.call('SET', revokedKey, '1', 'EX', ttl)
  redis.call('DEL', grantKey)
end
`;

const upsertScript = common + `
local key, bindingKey, grantKey, revokedKey, uidIndex, userCodeIndex = unpack(KEYS)
local id, raw, ttl, maxTtl, mode, bindingId = unpack(ARGV)
ttl, maxTtl = tonumber(ttl), tonumber(maxTtl)
local payload = decode(raw)
if not payload then return 0 end
local expires = now + ttl
if payload.exp ~= nil then
  if type(payload.exp) ~= 'number' or payload.exp <= now or payload.exp > now + maxTtl then return 0 end
  expires = math.min(expires, payload.exp)
end
if expires <= now then return 0 end
if redis.call('HGET', key, 'destroyed') then return 0 end
local previous = decode(redis.call('HGET', key, 'payload'))
if previous and (mode == 'grant' or mode == 'token' or previous.grantId) and (previous.accountId ~= payload.accountId or previous.clientId ~= payload.clientId or previous.grantId ~= payload.grantId) then return 0 end
if previous and mode ~= 'other' and tonumber(redis.call('HGET', key, 'expiresAt') or '0') <= now then return 0 end
local version = ''
if mode == 'grant' then
  if redis.call('EXISTS', revokedKey) == 1 then return 0 end
  version = redis.call('HGET', key, 'bindingVersion')
  if version then
    if redis.call('HGET', key, 'bindingId') ~= bindingId or redis.call('HGET', key, 'bindingKey') ~= bindingKey then return 0 end
  else
    version = redis.call('HGET', bindingKey, 'version')
  end
  if not version or not string.match(version, '^[1-9]%d*$') or redis.call('HGET', bindingKey, 'active') ~= '1' or redis.call('HGET', bindingKey, 'version') ~= version then return 0 end
elseif grantKey ~= '' then
  if redis.call('EXISTS', revokedKey) == 1 then return 0 end
  local parent = grant(grantKey)
  if not parent or parent.accountId ~= payload.accountId or parent.clientId ~= payload.clientId then return 0 end
elseif mode == 'token' then return 0 end
-- A stale upsert can never clear the separately stored consumption marker.
local consumed = redis.call('HGET', key, 'consumed')
if not consumed and payload.consumed then consumed = tostring(payload.consumed) end
removeIndexes(key, id)
local keepUntil = expires
if mode ~= 'other' then keepUntil = math.max(payload.exp, tonumber(redis.call('HGET', key, 'keepUntil') or '0'), previous and previous.exp or 0) end
redis.call('HSET', key, 'payload', raw, 'expiresAt', tostring(expires), 'keepUntil', tostring(keepUntil), 'grantKey', grantKey, 'revokedKey', revokedKey, 'uidIndex', uidIndex, 'userCodeIndex', userCodeIndex)
if mode == 'grant' then redis.call('HSET', key, 'bindingId', bindingId, 'bindingKey', bindingKey, 'bindingVersion', version) end
if consumed then redis.call('HSET', key, 'consumed', consumed) end
-- Never shorten security-marker retention when a payload expiry shrinks.
redis.call('EXPIREAT', key, keepUntil)
if uidIndex ~= '' then redis.call('SET', uidIndex, id, 'EXAT', expires) end
if userCodeIndex ~= '' then redis.call('SET', userCodeIndex, id, 'EXAT', expires) end
return 1
`;

const findScript = common + `
local payload, raw, bindingId, version = valid(KEYS[1], ARGV[1])
if not payload then return nil end
local consumed = redis.call('HGET', KEYS[1], 'consumed')
return {raw, consumed or '', bindingId or '', version or ''}
`;
const consumeScript = common + `
local consumed = redis.call('HGET', KEYS[1], 'consumed')
if consumed then
  local grantKey = redis.call('HGET', KEYS[1], 'grantKey')
  local revokedKey = redis.call('HGET', KEYS[1], 'revokedKey')
  if grantKey and grantKey ~= '' and revokedKey and revokedKey ~= '' then revoke(grantKey, revokedKey, ARGV[2]) end
  return 0
end
if not valid(KEYS[1], ARGV[1]) then return 0 end
redis.call('HSET', KEYS[1], 'consumed', tostring(now))
return 1
`;
const destroyScript = common + `
removeIndexes(KEYS[1], ARGV[1])
if ARGV[2] ~= 'other' then
  -- Also fence a destroy that precedes an in-flight first save.
  redis.call('HSET', KEYS[1], 'destroyed', '1', 'expiresAt', '0')
  redis.call('EXPIRE', KEYS[1], ARGV[3])
else redis.call('DEL', KEYS[1]) end
return 1
`;
const revokeScript = common + `
revoke(KEYS[1], KEYS[2], ARGV[1])
return 1
`;

/** Internal persistent adapter; the caller owns the connected official Redis client.
 * Set provider TTLs at or below maxTtlSeconds. Revocation markers live for that
 * maximum; security markers retain the highest accepted absolute expiry, so
 * delayed updates cannot resurrect an expired or destroyed record.
 */
export function createRedisAdapterFactory(options: RedisProviderAdapterOptions): new (model: string) => RedisProviderAdapter {
    validateStoreOptions(options);
    if (typeof options.invalidGrant !== 'function') throw new TypeError('Provider invalidGrant factory is required');
    const { command, maxTtlSeconds, invalidGrant } = options;
    const keys = createRedisKeys(options.namespace);

    async function execute(args: string[]): Promise<unknown> {
        try { return await command(args); }
        catch { throw new RedisStoreError(); }
    }
    const evaluate = (script: string, scriptKeys: string[], args: string[]) =>
        execute(['EVAL', script, String(scriptKeys.length), ...scriptKeys, ...args]);
    const text = (value: unknown): string => {
        if (typeof value !== 'string' || value.length === 0 || Buffer.byteLength(value) > 1024) throw new TypeError('Invalid provider identifier');
        return value;
    };
    const optionalText = (value: unknown): string => value === undefined ? '' : text(value);

    return class RedisProviderAdapter {
        readonly model: string;
        private readonly mode: string;
        constructor(model: string) {
            this.model = text(model);
            this.mode = model === 'Grant' ? 'grant' : requiresGrant.has(model) ? 'token' : grantable.has(model) ? 'grantable' : 'other';
        }
        async upsert(id: string, payload: Payload, expiresIn: number): Promise<void> {
            const recordKey = keys.record(this.model, text(id));
            if (!Number.isSafeInteger(expiresIn) || expiresIn <= 0 || expiresIn > maxTtlSeconds) throw new TypeError('Provider TTL exceeds storage policy');
            let raw: string;
            let snapshot: Payload;
            try {
                raw = JSON.stringify(payload);
                if (!raw || Buffer.byteLength(raw) > MAX_PAYLOAD_BYTES) throw new Error();
                snapshot = JSON.parse(raw) as Payload;
                if (!snapshot || typeof snapshot !== 'object' || Array.isArray(snapshot)) throw new Error();
            } catch { throw new TypeError('Invalid provider payload'); }
            if ((snapshot.exp !== undefined && (!Number.isSafeInteger(snapshot.exp) || Number(snapshot.exp) <= 0))
                || (this.mode !== 'other' && snapshot.exp === undefined)) throw new TypeError('Provider absolute expiry is required');
            if (snapshot.consumed !== undefined && (!Number.isSafeInteger(snapshot.consumed) || Number(snapshot.consumed) <= 0)) throw new TypeError('Invalid provider consumption marker');
            const bindingId = this.mode === 'grant' ? text(snapshot.accountId) : '';
            const grantId = grantable.has(this.model) ? optionalText(snapshot.grantId) : '';
            if (this.mode === 'token' && !grantId) throw new TypeError('Provider grant reference is required');
            if (this.mode === 'grant' || grantId) { text(snapshot.accountId); text(snapshot.clientId); }
            const uid = this.model === 'Session' ? optionalText(snapshot.uid) : '';
            const userCode = optionalText(snapshot.userCode);
            const result = await evaluate(upsertScript, [
                recordKey, bindingId ? keys.binding(bindingId) : '',
                grantId ? keys.record('Grant', grantId) : '',
                this.mode === 'grant' ? keys.revoked(id) : grantId ? keys.revoked(grantId) : '',
                uid ? keys.index(this.model, 'uid', uid) : '',
                userCode ? keys.index(this.model, 'userCode', userCode) : '',
            ], [id, raw, String(expiresIn), String(maxTtlSeconds), this.mode, bindingId]);
            if (result === 0) throw invalidGrant();
            if (result !== 1) throw new RedisStoreError();
        }
        private async read(model: string, id: string, mode: string): Promise<string[] | undefined> {
            const result = await evaluate(findScript, [keys.record(model, text(id))], [mode]);
            if (result === null) return undefined;
            if (!Array.isArray(result) || result.length !== 4 || result.some(value => typeof value !== 'string')) throw new RedisStoreError();
            return result as string[];
        }
        async find(id: string): Promise<Payload | undefined> {
            const result = await this.read(this.model, id, this.mode);
            if (!result) return undefined;
            try {
                const payload = JSON.parse(result[0]) as Payload;
                if (!payload || typeof payload !== 'object' || Array.isArray(payload)) throw new Error();
                if (result[1]) {
                    const consumed = Number(result[1]);
                    if (!Number.isSafeInteger(consumed) || consumed <= 0) throw new Error();
                    payload.consumed = consumed;
                }
                return payload;
            } catch { throw new RedisStoreError(); }
        }
        async getGrantBinding(grantId: string): Promise<{ bindingId: string; version: number } | undefined> {
            const result = await this.read('Grant', grantId, 'grant');
            if (!result) return undefined;
            const version = Number(result[3]);
            if (!result[2] || !Number.isSafeInteger(version) || version <= 0) throw new RedisStoreError();
            return { bindingId: result[2], version };
        }
        async findByUid(uid: string): Promise<Payload | undefined> { return this.findByIndex('uid', uid); }
        async findByUserCode(userCode: string): Promise<Payload | undefined> { return this.findByIndex('userCode', userCode); }
        private async findByIndex(field: string, value: string): Promise<Payload | undefined> {
            const id = await execute(['GET', keys.index(this.model, field, text(value))]);
            if (id === null) return undefined;
            if (typeof id !== 'string') throw new RedisStoreError();
            const payload = await this.find(id);
            return payload?.[field] === value ? payload : undefined;
        }
        async consume(id: string): Promise<void> {
            const result = await evaluate(consumeScript, [keys.record(this.model, text(id))], [this.mode, String(maxTtlSeconds)]);
            if (result === 0) throw invalidGrant();
            if (result !== 1) throw new RedisStoreError();
        }
        async destroy(id: string): Promise<void> {
            if (this.model === 'Grant') { await this.revokeByGrantId(id); return; }
            const result = await evaluate(destroyScript, [keys.record(this.model, text(id))], [id, this.model === 'Session' ? 'session' : this.mode, String(maxTtlSeconds)]);
            if (result !== 1) throw new RedisStoreError();
        }
        async revokeByGrantId(grantId: string): Promise<void> {
            text(grantId);
            const result = await evaluate(revokeScript, [keys.record('Grant', grantId), keys.revoked(grantId)], [String(maxTtlSeconds)]);
            if (result !== 1) throw new RedisStoreError();
        }
    };
}
